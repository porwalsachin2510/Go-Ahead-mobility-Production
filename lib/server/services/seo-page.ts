export type EntitySeo = {
  title?: string
  description?: string
  canonical?: string
  noindex?: boolean
  nofollow?: boolean
  ogTitle?: string
  ogDescription?: string
  ogImage?: string
  faq?: { question: string; answer: string }[]
  schemaJson?: string
}

export type DetailInput = {
  kind: TemplateKind
  path: string
  name: string
  summary?: string
  bodyText?: string
  image?: string
  seo?: EntitySeo | null
  type?: 'website' | 'article'
  publishedTime?: string | null
  modifiedTime?: string | null
  authors?: string[]
}

/**
 * Programmatic detail pages (industries, case studies, resources) only become indexable once they carry
 * enough real copy. The same rule is applied by the inventory, so sitemap, audit and robots meta agree.
 */
export function thinContentReason(site: SeoSettings, wordCount: number): string {
  const min = site.indexing?.minWords ?? 0
  return min > 0 && wordCount < min ? `Only ${wordCount} words; the publication rule requires at least ${min} before this page is indexable.` : ''
}

export function wordCountOf(...texts: (string | undefined | null)[]) {
  return texts.reduce((n, t) => n + countWords(stripMarkdown(t ?? '')), 0)
}

export async function detailMetadata(input: DetailInput): Promise<Metadata> {
  const { site } = await getSeoSettings()
  const seo = input.seo ?? {}
  const eff = resolveEffectiveSeo(input.kind, site, { name: input.name, summary: input.summary, explicitTitle: seo.title, explicitDescription: seo.description })
  const thin = thinContentReason(site, wordCountOf(input.name, input.bodyText))
  return buildMetadata({
    site,
    path: input.path,
    title: eff.title,
    description: eff.description,
    canonical: seo.canonical,
    noindex: Boolean(seo.noindex) || Boolean(thin),
    nofollow: seo.nofollow,
    ogTitle: seo.ogTitle,
    ogDescription: seo.ogDescription,
    ogImage: seo.ogImage || input.image,
    ogImageAlt: input.name,
    type: input.type,
    publishedTime: input.publishedTime ?? undefined,
    modifiedTime: input.modifiedTime ?? undefined,
    authors: input.authors,
  })
}


function canonicalRoutePath(path: string) {
  if (path === '/company/about-us') return '/about-us'
  if (path === '/learn') return '/resources'
  return path
}

/** Applies route-level SEO overrides to the metadata generated by the dedicated route. */
export async function applyRouteSeoMetadata(
  rawPath: string,
  base: Metadata,
  options: { preserveNoindex?: boolean } = {},
): Promise<Metadata> {
  const path = canonicalRoutePath(rawPath)
  const [{ site }, record] = await Promise.all([
    getSeoSettings(),
    RouteSeo.findOne({ path }).lean<any>(),
  ])
  if (!record?.seo) return base

  const seo = record.seo
  const openGraph = (base.openGraph ?? {}) as Record<string, any>
  const baseTitleValue = (base as any).title
  const baseTitle = typeof baseTitleValue === 'string'
    ? baseTitleValue
    : typeof baseTitleValue?.absolute === 'string'
      ? baseTitleValue.absolute
      : typeof baseTitleValue?.default === 'string'
        ? baseTitleValue.default
        : site.defaultTitle
  const baseDescription = typeof base.description === 'string' ? base.description : ''
  const baseImages = openGraph.images
  const firstImage = Array.isArray(baseImages) ? baseImages[0] : baseImages
  const baseImage = typeof firstImage === 'string' ? firstImage : firstImage?.url ? String(firstImage.url) : ''
  const baseCanonical = (base.alternates as any)?.canonical
  const baseRobots = (base as any).robots ?? {}
  const metadata = buildMetadata({
    site,
    path,
    title: seo.title || baseTitle,
    description: seo.description || baseDescription,
    canonical: seo.canonical || (baseCanonical ? String(baseCanonical) : ''),
    noindex: Boolean(seo.noindex) || Boolean(options.preserveNoindex),
    nofollow: Boolean(seo.nofollow),
    ogTitle: seo.ogTitle || openGraph.title,
    ogDescription: seo.ogDescription || openGraph.description,
    ogImage: seo.ogImage || baseImage,
    ogImageAlt: firstImage?.alt || openGraph.title || baseTitle,
    type: openGraph.type === 'article' ? 'article' : 'website',
  })
  // When a listing is filtered or intentionally too thin to index, keep its route-level
  // noindex decision even if a metadata override exists.
  if (options.preserveNoindex && baseRobots) metadata.robots = baseRobots
  return { ...base, ...metadata }
}

/** Extra route-level FAQ/custom JSON-LD, emitted in the initial HTML response. */
export async function routeSeoJsonLd(rawPath: string): Promise<JsonLd[]> {
  const path = canonicalRoutePath(rawPath)
  const [{ site }, record] = await Promise.all([
    getSeoSettings(),
    RouteSeo.findOne({ path }).lean<any>(),
  ])
  const nodes = entitySchemaNodes(site, path, record?.seo)
  // The public FAQ route already emits FAQPage from its actual published questions.
  // Keep route-level custom JSON-LD there, but avoid outputting a second FAQPage node.
  return path === '/faq' ? nodes.filter((node) => node['@type'] !== 'FAQPage') : nodes
}

export type Crumb = { name: string; path: string }

/** Returns the first hub path that is a live CMS page, so breadcrumbs never link to a 404. */
export async function liveHub(candidates: { name: string; path: string }[]): Promise<Crumb | null> {
  for (const c of candidates) {
    const page = await getPublishedPage(c.path)
    if (page) return { name: page.title || c.name, path: c.path }
  }
  return null
}

export async function detailJsonLd(input: { path: string; name: string; description?: string; modified?: string | null; trail: Crumb[]; extra?: (JsonLd | null)[]; seo?: EntitySeo | null }) {
  const { site } = await getSeoSettings()
  return [
    webPageSchema(site, { path: input.path, name: input.name, description: input.description, modified: input.modified }),
    breadcrumbSchema(site, input.trail),
    ...(input.extra ?? []),
    ...entitySchemaNodes(site, input.path, input.seo),
  ].filter(Boolean) as JsonLd[]
}
