const MODELS: Partial<Record<EntityType, any>> = { page: Page, route: RouteSeo, post: Post, industry: Industry, case_study: CaseStudy, resource: Resource, job: Job }

const text = (max: number) => z.string().trim().max(max).default('')

export const seoFieldsSchema = z.object({
  title: text(200),
  description: text(400),
  canonical: text(500),
  noindex: z.boolean().default(false),
  nofollow: z.boolean().default(false),
  ogTitle: text(200),
  ogDescription: text(400),
  ogImage: text(500),
  focusKeyword: text(120),
  keywords: z.array(z.string().trim().min(1).max(80)).max(10).default([]),
  faq: z
    .array(z.object({ question: z.string().trim().min(1).max(300), answer: z.string().trim().min(1).max(2000) }))
    .max(20)
    .default([]),
  schemaJson: z.string().max(10000).default(''),
})

export const entitySeoSchema = z.object({ key: z.string().min(1).max(200), seo: seoFieldsSchema })

export type SeoFields = z.infer<typeof seoFieldsSchema>

export const EMPTY_SEO: SeoFields = { title: '', description: '', canonical: '', noindex: false, nofollow: false, ogTitle: '', ogDescription: '', ogImage: '', focusKeyword: '', keywords: [], faq: [], schemaJson: '' }

/** Pages keep separate draft and published content; every other type stores SEO at the top level. */
function seoOf(entityType: EntityType, doc: any) {
  if (!doc) return {}
  if (entityType === 'page') return doc.published?.seo ?? doc.draft?.seo ?? {}
  return doc.seo ?? {}
}

function storesSeo(entityType: EntityType, Model: any) {
  if (!Model) return false
  return entityType === 'page' ? Boolean(Model.schema.path('draft.seo')) : Boolean(Model.schema.path('seo'))
}

function validateCanonical(raw: string, siteUrl: string): string {
  if (!raw) return ''
  if (raw.startsWith('/') && !raw.startsWith('//')) {
    if (/[?#\s]/.test(raw)) throw badRequest('Canonical paths cannot contain query strings, fragments or spaces')
    return raw
  }
  let url: URL
  try {
    url = new URL(raw)
  } catch {
    throw badRequest('Canonical must be a relative path or an absolute https URL')
  }
  if (url.protocol !== 'https:') throw badRequest('Canonical URLs must use https')
  const siteHost = (() => {
    try {
      return new URL(siteUrl).host
    } catch {
      return ''
    }
  })()
  if (siteHost && url.host !== siteHost) throw badRequest(`Cross-domain canonicals are not allowed here. Use ${siteHost}.`)
  return url.toString()
}

function validateImage(raw: string): string {
  if (!raw) return ''
  if (raw.startsWith('/') && !raw.startsWith('//')) return raw
  if (/^https:\/\/[^\s]+$/.test(raw)) return raw
  throw badRequest('Social image must be a relative path or https URL')
}

async function findEditable(key: string) {
  await connectDb()
  const snapshot = await buildInventory()
  const entry = snapshot.entries.find((e) => e.key === key)
  if (!entry) throw notFound('Page')
  const Model = MODELS[entry.entityType]
  const editable = entry.editable && Boolean(entry.entityId) && (entry.entityType === 'route' || storesSeo(entry.entityType, Model))
  return { snapshot, entry, Model, editable }
}

export async function updateEntitySeo(input: z.infer<typeof entitySeoSchema>, userId?: string) {
  const { entry, Model, editable } = await findEditable(input.key)
  if (!editable) throw badRequest('This route is generated by code and has no editable SEO record.')

  const { site } = await getSeoSettings()
  const custom = parseCustomJsonLd(input.seo.schemaJson)
  if (custom.errors.length) throw badRequest(`Structured data: ${custom.errors.join(' ')}`)
  const keywords = [...new Map(input.seo.keywords.map((k) => [fold(k), k])).values()].filter((k) => fold(k) !== fold(input.seo.focusKeyword))
  const seo: SeoFields = {
    ...input.seo,
    keywords,
    schemaJson: custom.nodes.length ? JSON.stringify(custom.nodes.length === 1 ? custom.nodes[0] : custom.nodes, null, 2) : '',
    canonical: validateCanonical(input.seo.canonical, site.siteUrl),
    ogImage: validateImage(input.seo.ogImage),
  }

  const before = entry.entityType === 'route'
    ? await RouteSeo.findOne({ path: entry.path }).lean()
    : await Model.findById(entry.entityId).lean()
  if (!before && entry.entityType !== 'route') throw notFound('Content record')
  if (entry.entityType === 'route') {
    await RouteSeo.findOneAndUpdate(
      { path: entry.path },
      { $set: { seo, updatedById: userId ?? null }, $setOnInsert: { path: entry.path } },
      { upsert: true, returnDocument: 'after', runValidators: true },
    )
  } else {
    const set: Record<string, unknown> = entry.entityType === 'page' ? { 'draft.seo': seo, ...((before as any).published ? { 'published.seo': seo } : {}) } : { seo }
    await Model.updateOne({ _id: entry.entityId }, { $set: set }, { runValidators: true })
  }
  revalidatePath(entry.path)
  revalidatePath('/sitemap.xml')
  return { entry, before: seoOf(entry.entityType, before), after: seo }
}

const SKIP_KEYS = new Set(['_id', 'id', 'type', 'seo', 'image', 'images', 'src', 'href', 'url', 'slug', 'icon', 'variant', 'hidden', 'heroImage', 'avatar', 'createdAt', 'updatedAt', 'authorId', 'categoryIds', 'tagIds', 'state', 'status', 'path', 'parentPath', 'searchText'])

/** Collects human-readable copy from a content record (any shape of blocks or fields) for keyword analysis. */
function collectText(value: unknown, out: string[], depth = 0) {
  if (depth > 8 || value == null) return
  if (typeof value === 'string') {
    const t = value.trim()
    if (t && !/^(https?:|\/|#|[0-9a-f]{24}$)/i.test(t)) out.push(stripMarkdown(t))
    return
  }
  if (Array.isArray(value)) return value.forEach((v) => collectText(v, out, depth + 1))
  if (typeof value === 'object') {
    if (value instanceof Date) return
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) if (!SKIP_KEYS.has(k)) collectText(v, out, depth + 1)
  }
}

function bodyTextOf(entityType: EntityType, doc: any) {
  const out: string[] = []
  if (entityType === 'page') collectText((doc.published ?? doc.draft)?.blocks, out)
  else if (entityType === 'post') {
    if (doc.excerpt) out.push(doc.excerpt)
    out.push(stripMarkdown(doc.content ?? ''))
  } else {
    const { title: _t, name: _n, seo: _s, ...rest } = doc
    collectText(rest, out)
  }
  return out.join('\n\n').slice(0, 60000)
}

/** Every URL whose focus keyword matches, so the editor can warn about cannibalisation. */
async function keywordOwners(paths: Map<string, string>) {
  const owners: { keyword: string; path: string }[] = []
  await Promise.all(
    (Object.entries(MODELS) as [EntityType, any][]).map(async ([type, Model]) => {
      const field = type === 'page' ? 'published.seo.focusKeyword' : 'seo.focusKeyword'
      const projection = { [field]: 1, ...(type === 'route' ? { path: 1 } : {}) }
      const docs = await Model.find({ [field]: { $nin: ['', null] } }, projection).lean()
      for (const d of docs as any[]) {
        const path = type === 'route' ? String(d.path ?? '') : paths.get(String(d._id))
        const kw = seoOf(type, d).focusKeyword
        if (path && kw) owners.push({ keyword: kw, path })
      }
    }),
  )
  return owners
}

export async function getEntitySeo(key: string) {
  const { snapshot, entry, Model, editable } = await findEditable(key)
  if (!editable) return { editable: false, seo: null }
  const doc = entry.entityType === 'route'
    ? await RouteSeo.findOne({ path: entry.path }).lean()
    : await Model.findById(entry.entityId).lean()
  if (!doc && entry.entityType !== 'route') throw notFound('Content record')
  const paths = new Map(snapshot.entries.filter((e) => e.entityId && e.entityType !== 'route').map((e) => [String(e.entityId), e.path]))
  const owners = await keywordOwners(paths)
  const stored = seoOf(entry.entityType, doc)
  const routeDefaults = entry.entityType === 'route' && !doc ? { noindex: !entry.indexable } : {}
  return {
    editable: true,
    seo: { ...EMPTY_SEO, ...routeDefaults, ...stored, faq: (stored.faq ?? []).map((f: any) => ({ question: f.question ?? '', answer: f.answer ?? '' })), keywords: stored.keywords ?? [] },
    context: {
      path: entry.path,
      effectiveTitle: entry.title,
      effectiveDescription: entry.description,
      headings: entry.headings,
      images: entry.images,
      links: entry.links,
      bodyText: entry.entityType === 'route' ? entry.headings.map((h) => h.text).join('\n') : bodyTextOf(entry.entityType, doc),
      minWords: snapshot.site.indexing.minWords,
      siteHost: (() => {
        try {
          return new URL(snapshot.site.siteUrl).host
        } catch {
          return ''
        }
      })(),
    },
    keywordOwners: owners.filter((o) => o.path !== entry.path),
  }
}

export const issueActionSchema = z.object({
  action: z.enum(['ignore', 'restore']),
  entityKey: z.string().min(1).max(200),
  code: z.string().min(1).max(80),
  evidence: z.string().max(2000).default(''),
  reason: z.string().trim().max(400).default(''),
})

export async function setIssueState(input: z.infer<typeof issueActionSchema>, userId: string) {
  await connectDb()
  if (input.action === 'restore') {
    await SeoIssueState.deleteOne({ entityKey: input.entityKey, code: input.code })
    return
  }
  const hash = evidenceHash({ entityKey: input.entityKey, code: input.code, evidence: input.evidence } as AuditIssue)
  await SeoIssueState.updateOne(
    { entityKey: input.entityKey, code: input.code },
    { $set: { evidenceHash: hash, status: 'ignored', reason: input.reason, byId: userId } },
    { upsert: true },
  )
}
