'use client'

import { useRouter } from 'next/navigation'
import { useMemo, useState } from 'react'
import { Card, FieldShell, Input, Textarea } from '@/components/admin/ui'
import { Button } from '@/components/ui/button'
import { parseCustomJsonLd } from '@/lib/seo/entity-schema'
import { analyzeKeyword, fold, type AnalysisCheck } from '@/lib/seo/keyword-analysis'
import type { HeadingRef, ImageRef, LinkRef } from '@/lib/seo/types'

type Faq = { question: string; answer: string }
export type SeoFields = {
  title: string
  description: string
  canonical: string
  noindex: boolean
  nofollow: boolean
  ogTitle: string
  ogDescription: string
  ogImage: string
  focusKeyword: string
  keywords: string[]
  faq: Faq[]
  schemaJson: string
}
type Context = { path: string; effectiveTitle: string; effectiveDescription: string; headings: HeadingRef[]; images: ImageRef[]; links: LinkRef[]; bodyText: string; minWords: number; siteHost: string }
type Loaded = { seo: SeoFields; context: Context; keywordOwners: { keyword: string; path: string }[] }
type Tab = 'search' | 'keyword' | 'schema'

const STATUS_STYLE: Record<AnalysisCheck['status'], string> = {
  pass: 'bg-primary/10 text-primary',
  warn: 'bg-muted text-foreground',
  fail: 'bg-destructive/10 text-destructive',
}
const STATUS_LABEL: Record<AnalysisCheck['status'], string> = { pass: 'Good', warn: 'Improve', fail: 'Problem' }

export function SeoEditor({ entityKey, path, siteUrl, onClose }: { entityKey: string; path: string; siteUrl: string; onClose: () => void }) {
  const router = useRouter()
  const [data, setData] = useState<Loaded | null>(null)
  const [seo, setSeo] = useState<SeoFields | null>(null)
  const [loadError, setLoadError] = useState('')
  const [requested, setRequested] = useState(false)
  const [saving, setSaving] = useState(false)
  const [message, setMessage] = useState('')
  const [tab, setTab] = useState<Tab>('search')
  const [newKeyword, setNewKeyword] = useState('')

  if (!requested) {
    setRequested(true)
    fetch(`/api/v1/admin/seo/entity?key=${encodeURIComponent(entityKey)}`)
      .then((r) => r.json())
      .then((body) => {
        const d = body.data ?? body
        if (!d.editable) return setLoadError('This route is generated by code and has no editable SEO record.')
        setData(d)
        setSeo(d.seo)
      })
      .catch(() => setLoadError('Could not load SEO fields.'))
  }

  const set = <K extends keyof SeoFields>(k: K, v: SeoFields[K]) => setSeo((s) => (s ? { ...s, [k]: v } : s))

  const title = seo?.title || data?.context.effectiveTitle || ''
  const description = seo?.description || data?.context.effectiveDescription || ''

  const analysis = useMemo(() => {
    if (!seo || !data) return null
    const kw = fold(seo.focusKeyword.trim())
    return analyzeKeyword({
      keyword: seo.focusKeyword,
      secondary: seo.keywords,
      title,
      description,
      path: data.context.path,
      bodyText: data.context.bodyText,
      headings: data.context.headings,
      images: data.context.images,
      links: data.context.links,
      siteHost: data.context.siteHost,
      minWords: data.context.minWords,
      competingPaths: kw ? data.keywordOwners.filter((o) => fold(o.keyword.trim()) === kw).map((o) => o.path) : [],
    })
  }, [seo, data, title, description])

  const schemaCheck = useMemo(() => parseCustomJsonLd(seo?.schemaJson ?? ''), [seo?.schemaJson])

  async function save() {
    if (!seo) return
    setSaving(true)
    setMessage('')
    const res = await fetch('/api/v1/admin/seo/entity', { method: 'PATCH', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ key: entityKey, seo: { ...seo, faq: seo.faq.filter((f) => f.question.trim() && f.answer.trim()) } }) })
    const body = await res.json().catch(() => ({}))
    setSaving(false)
    if (!res.ok) return setMessage(body?.error?.message || 'Save failed')
    const saved = body.data?.seo ?? body.seo
    if (saved) setSeo((s) => (s ? { ...s, ...saved } : s))
    setMessage('Saved. The live page has been revalidated.')
    router.refresh()
  }

  function addKeyword() {
    const k = newKeyword.trim()
    if (!seo || !k || seo.keywords.length >= 10 || seo.keywords.some((x) => fold(x) === fold(k))) return
    set('keywords', [...seo.keywords, k])
    setNewKeyword('')
  }

  const host = (() => {
    try {
      return new URL(siteUrl).host
    } catch {
      return siteUrl
    }
  })()
  const crumbs = `${host}${path === '/' ? '' : ` › ${path.split('/').filter(Boolean).join(' › ')}`}`

  return (
    <div role="dialog" aria-modal="true" aria-labelledby="seo-editor-title" className="fixed inset-0 z-50 flex justify-end bg-foreground/40" onKeyDown={(e) => e.key === 'Escape' && onClose()}>
      <div className="flex h-full w-full max-w-3xl flex-col overflow-hidden bg-background shadow-xl">
        <div className="flex items-start justify-between gap-4 border-b border-border p-5">
          <div className="min-w-0">
            <h2 id="seo-editor-title" className="font-display text-lg font-semibold">Edit SEO</h2>
            <p className="break-all font-mono text-xs text-muted-foreground">{path}</p>
          </div>
          <div className="flex items-center gap-3">
            {analysis && <ScoreBadge score={analysis.score} />}
            <Button variant="ghost" size="sm" onClick={onClose} autoFocus>Close</Button>
          </div>
        </div>

        {loadError && <p role="alert" className="p-5 text-sm text-destructive">{loadError}</p>}
        {!seo && !loadError && <p className="p-5 text-sm text-muted-foreground">Loading…</p>}

        {seo && data && analysis && (
          <>
            <div role="tablist" aria-label="SEO sections" className="flex gap-1 border-b border-border px-5">
              {([
                ['search', 'Search & social'],
                ['keyword', `Keyword analysis`],
                ['schema', 'Structured data'],
              ] as [Tab, string][]).map(([id, label]) => (
                <button
                  key={id}
                  role="tab"
                  type="button"
                  id={`tab-${id}`}
                  aria-selected={tab === id}
                  aria-controls={`panel-${id}`}
                  onClick={() => setTab(id)}
                  className={`-mb-px border-b-2 px-3 py-2.5 text-sm font-medium ${tab === id ? 'border-primary text-foreground' : 'border-transparent text-muted-foreground hover:text-foreground'}`}
                >
                  {label}
                </button>
              ))}
            </div>

            <div className="flex flex-1 flex-col gap-5 overflow-y-auto p-5">
              {tab === 'search' && (
                <div role="tabpanel" id="panel-search" aria-labelledby="tab-search" className="flex flex-col gap-5">
                  <section aria-label="Search result preview" className="flex flex-col gap-2">
                    <h3 className="text-sm font-medium">Search result preview</h3>
                    <div className="grid gap-3 md:grid-cols-2">
                      {(['Desktop', 'Mobile'] as const).map((d) => (
                        <Card key={d} className="flex flex-col gap-1 p-4">
                          <span className="text-xs font-medium text-muted-foreground">{d}</span>
                          <span className="truncate text-xs text-muted-foreground">{crumbs}</span>
                          <span className="line-clamp-2 text-base font-medium text-primary">{clip(title, d === 'Desktop' ? 60 : 70)}</span>
                          <span className="line-clamp-3 text-sm leading-relaxed text-muted-foreground"><Highlight text={clip(description || 'No description: search engines will pick text from the page.', d === 'Desktop' ? 158 : 120)} keyword={seo.focusKeyword} /></span>
                        </Card>
                      ))}
                    </div>
                  </section>

                  <FieldShell id="seo-title" label="SEO title" help={lengthHint(seo.title, 30, 60, 'Blank uses the template. ')}>
                    <Input id="seo-title" value={seo.title} maxLength={200} onChange={(e) => set('title', e.target.value)} placeholder={data.context.effectiveTitle} />
                  </FieldShell>
                  <FieldShell id="seo-desc" label="Meta description" help={lengthHint(seo.description, 70, 160, '')}>
                    <Textarea id="seo-desc" rows={3} value={seo.description} maxLength={400} onChange={(e) => set('description', e.target.value)} placeholder={data.context.effectiveDescription} />
                  </FieldShell>
                  <FieldShell id="seo-canonical" label="Canonical override" help="Blank means self-canonical. Use a path like /services/x or an https URL on this domain.">
                    <Input id="seo-canonical" value={seo.canonical} onChange={(e) => set('canonical', e.target.value)} placeholder={path} />
                  </FieldShell>
                  <fieldset className="flex flex-wrap gap-6 text-sm">
                    <legend className="mb-2 text-sm font-medium">Robots</legend>
                    <label className="flex items-center gap-2"><input type="checkbox" checked={seo.noindex} onChange={(e) => set('noindex', e.target.checked)} /> noindex (removes from sitemap)</label>
                    <label className="flex items-center gap-2"><input type="checkbox" checked={seo.nofollow} onChange={(e) => set('nofollow', e.target.checked)} /> nofollow</label>
                  </fieldset>

                  <section aria-label="Social share preview" className="flex flex-col gap-3">
                    <h3 className="text-sm font-medium">Social share preview</h3>
                    <Card className="overflow-hidden">
                      {seo.ogImage ? (
                        // eslint-disable-next-line @next/next/no-img-element
                        <img src={seo.ogImage} alt="" className="aspect-[1200/630] w-full bg-muted object-cover" />
                      ) : (
                        <div className="flex aspect-[1200/630] w-full items-center justify-center bg-muted px-6 text-center text-xs text-muted-foreground">No social image set. The page image or site default is used.</div>
                      )}
                      <div className="flex flex-col gap-0.5 border-t border-border p-3">
                        <span className="text-xs uppercase text-muted-foreground">{host}</span>
                        <span className="line-clamp-1 text-sm font-semibold">{seo.ogTitle || title}</span>
                        <span className="line-clamp-2 text-xs text-muted-foreground">{seo.ogDescription || description}</span>
                      </div>
                    </Card>
                  </section>
                  <FieldShell id="og-title" label="Social title">
                    <Input id="og-title" value={seo.ogTitle} maxLength={200} onChange={(e) => set('ogTitle', e.target.value)} placeholder={title} />
                  </FieldShell>
                  <FieldShell id="og-desc" label="Social description">
                    <Textarea id="og-desc" rows={2} value={seo.ogDescription} maxLength={400} onChange={(e) => set('ogDescription', e.target.value)} />
                  </FieldShell>
                  <FieldShell id="og-image" label="Social image" help="1200×630 recommended. Relative path or https URL.">
                    <Input id="og-image" value={seo.ogImage} onChange={(e) => set('ogImage', e.target.value)} placeholder="/api/v1/media/…" />
                  </FieldShell>
                </div>
              )}

              {tab === 'keyword' && (
                <div role="tabpanel" id="panel-keyword" aria-labelledby="tab-keyword" className="flex flex-col gap-5">
                  <FieldShell id="seo-kw" label="Focus keyword" help="The main search phrase this page should rank for. Analysis updates as you type and uses the published content.">
                    <Input id="seo-kw" value={seo.focusKeyword} maxLength={120} onChange={(e) => set('focusKeyword', e.target.value)} placeholder="e.g. corporate housing in Mumbai" />
                  </FieldShell>

                  <div className="flex flex-col gap-2">
                    <label htmlFor="seo-kw2" className="text-sm font-medium">Secondary keywords</label>
                    <div className="flex gap-2">
                      <Input
                        id="seo-kw2"
                        value={newKeyword}
                        maxLength={80}
                        onChange={(e) => setNewKeyword(e.target.value)}
                        onKeyDown={(e) => {
                          if (e.key === 'Enter' && !e.nativeEvent.isComposing && e.keyCode !== 229) {
                            e.preventDefault()
                            addKeyword()
                          }
                        }}
                        placeholder="Synonym or related phrase"
                      />
                      <Button type="button" variant="outline" onClick={addKeyword} disabled={seo.keywords.length >= 10}>Add</Button>
                    </div>
                    {analysis.secondary.length > 0 && (
                      <ul className="flex flex-wrap gap-2">
                        {analysis.secondary.map((k) => (
                          <li key={k.keyword} className="flex items-center gap-2 rounded-md border border-border px-2 py-1 text-xs">
                            <span>{k.keyword}</span>
                            <span className="text-muted-foreground">{k.occurrences}×</span>
                            <button type="button" aria-label={`Remove ${k.keyword}`} className="text-muted-foreground hover:text-destructive" onClick={() => set('keywords', seo.keywords.filter((x) => x !== k.keyword))}>×</button>
                          </li>
                        ))}
                      </ul>
                    )}
                  </div>

                  <dl className="grid grid-cols-2 gap-3 sm:grid-cols-4">
                    <Stat label="SEO score" value={`${analysis.score}`} />
                    <Stat label="Words" value={`${analysis.wordCount}`} />
                    <Stat label="Density" value={`${analysis.density}%`} />
                    <Stat label="Readability" value={`${analysis.readability.score}`} hint={analysis.readability.label} />
                  </dl>

                  {(['keyword', 'meta', 'content', 'links'] as const).map((group) => {
                    const items = analysis.checks.filter((c) => c.group === group)
                    if (!items.length) return null
                    return (
                      <section key={group} aria-labelledby={`grp-${group}`} className="flex flex-col gap-2">
                        <h3 id={`grp-${group}`} className="text-sm font-medium capitalize">{group === 'meta' ? 'Title and description' : group}</h3>
                        <Card className="flex flex-col divide-y divide-border">
                          {items.map((c) => (
                            <div key={c.id} className="flex items-start gap-3 p-3 text-sm">
                              <span className={`shrink-0 rounded px-1.5 py-0.5 text-xs font-medium ${STATUS_STYLE[c.status]}`}>{STATUS_LABEL[c.status]}</span>
                              <div className="flex min-w-0 flex-col">
                                <span className="font-medium">{c.label}</span>
                                <span className="text-pretty text-muted-foreground">{c.detail}</span>
                              </div>
                            </div>
                          ))}
                        </Card>
                      </section>
                    )
                  })}
                </div>
              )}

              {tab === 'schema' && (
                <div role="tabpanel" id="panel-schema" aria-labelledby="tab-schema" className="flex flex-col gap-5">
                  <section aria-labelledby="faq-heading" className="flex flex-col gap-3">
                    <div className="flex items-center justify-between gap-3">
                      <div>
                        <h3 id="faq-heading" className="text-sm font-medium">FAQ (FAQPage schema)</h3>
                        <p className="text-xs text-muted-foreground">Questions should also be visible on the page. Search engines ignore FAQ markup that does not match visible content.</p>
                      </div>
                      <Button type="button" variant="outline" size="sm" disabled={seo.faq.length >= 20} onClick={() => set('faq', [...seo.faq, { question: '', answer: '' }])}>Add question</Button>
                    </div>
                    {seo.faq.length === 0 && <p className="text-sm text-muted-foreground">No FAQ items.</p>}
                    {seo.faq.map((f, i) => (
                      <Card key={i} className="flex flex-col gap-2 p-3">
                        <label className="sr-only" htmlFor={`faq-q-${i}`}>Question {i + 1}</label>
                        <Input id={`faq-q-${i}`} value={f.question} maxLength={300} placeholder={`Question ${i + 1}`} onChange={(e) => set('faq', seo.faq.map((x, j) => (j === i ? { ...x, question: e.target.value } : x)))} />
                        <label className="sr-only" htmlFor={`faq-a-${i}`}>Answer {i + 1}</label>
                        <Textarea id={`faq-a-${i}`} rows={2} value={f.answer} maxLength={2000} placeholder="Answer" onChange={(e) => set('faq', seo.faq.map((x, j) => (j === i ? { ...x, answer: e.target.value } : x)))} />
                        <div className="flex justify-end">
                          <Button type="button" variant="ghost" size="sm" onClick={() => set('faq', seo.faq.filter((_, j) => j !== i))}>Remove</Button>
                        </div>
                      </Card>
                    ))}
                  </section>

                  <FieldShell id="seo-schema" label="Custom JSON-LD" help='Paste one schema.org object, an array, or an @graph (e.g. Service, Product, HowTo, Event, LocalBusiness). Organization, WebSite and breadcrumbs are generated automatically.'>
                    <Textarea id="seo-schema" rows={12} value={seo.schemaJson} onChange={(e) => set('schemaJson', e.target.value)} className="font-mono text-xs" placeholder={'{\n  "@type": "Service",\n  "name": "Corporate housing",\n  "areaServed": "Mumbai"\n}'} spellCheck={false} />
                  </FieldShell>
                  <p role="status" aria-live="polite" className={`text-sm ${schemaCheck.errors.length ? 'text-destructive' : 'text-muted-foreground'}`}>
                    {schemaCheck.errors.length ? schemaCheck.errors.join(' ') : schemaCheck.types.length ? `Valid: ${schemaCheck.types.join(', ')}` : 'No custom structured data.'}
                  </p>
                  <a href={`https://search.google.com/test/rich-results?url=${encodeURIComponent(`${siteUrl}${path === '/' ? '/' : path}`)}`} target="_blank" rel="noreferrer" className="text-sm underline">
                    Test the live URL in Google&apos;s Rich Results Test
                  </a>
                </div>
              )}
            </div>

            <div className="flex items-center gap-3 border-t border-border p-5">
              <Button onClick={save} disabled={saving || schemaCheck.errors.length > 0}>{saving ? 'Saving…' : 'Save SEO'}</Button>
              <span role="status" aria-live="polite" className="text-sm text-muted-foreground">{message}</span>
            </div>
          </>
        )}
      </div>
    </div>
  )
}

function ScoreBadge({ score }: { score: number }) {
  const tone = score >= 75 ? 'bg-primary text-primary-foreground' : score >= 50 ? 'bg-muted text-foreground' : 'bg-destructive text-primary-foreground'
  return <span className={`rounded-md px-2 py-1 text-sm font-semibold tabular-nums ${tone}`} aria-label={`SEO score ${score} out of 100`}>{score}</span>
}

function Stat({ label, value, hint }: { label: string; value: string; hint?: string }) {
  return (
    <Card className="flex flex-col gap-0.5 p-3">
      <dt className="text-xs text-muted-foreground">{label}</dt>
      <dd className="font-display text-xl font-semibold tabular-nums">{value}</dd>
      {hint && <dd className="text-xs text-muted-foreground">{hint}</dd>}
    </Card>
  )
}

function Highlight({ text, keyword }: { text: string; keyword: string }) {
  const k = keyword.trim()
  if (!k) return <>{text}</>
  const i = fold(text).indexOf(fold(k))
  if (i < 0) return <>{text}</>
  return (
    <>
      {text.slice(0, i)}
      <strong className="font-semibold text-foreground">{text.slice(i, i + k.length)}</strong>
      {text.slice(i + k.length)}
    </>
  )
}

function clip(s: string, n: number) {
  return s.length > n ? `${s.slice(0, n - 1).trimEnd()}…` : s
}

function lengthHint(v: string, min: number, max: number, prefix: string) {
  const n = v.length
  if (!n) return `${prefix}Aim for roughly ${min}–${max} characters.`
  if (n < min) return `${n} characters: may be too short to be descriptive.`
  if (n > max) return `${n} characters: likely to be truncated in results.`
  return `${n} characters.`
}
